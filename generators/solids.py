# Materials for surfaces with no picture, drawn in one solid colour: a stone made from noise alone,
# its grain a grey that multiplies the surface's own colour, with its normal, roughness and
# occlusion. The client lays them along the world's three axes, since such a surface has no
# picture coordinates. Each is written as a [[solid]] entry in a pack folder's manifest, replacing
# this script's earlier entries.
# solids.py <pack folder>
import os, re, subprocess, sys
import numpy as np
from scipy import ndimage

TOOL = 'solids.py'
N = 512
# name: surfaces, their solid colour (ARGB), metres one repeat covers on the object at its own
# size (it grows with the object's scale), look, seed.
# The Bael'Zharon statues: one dark red, End of Retail's surface and the 2005 files' for it. Half a
# metre is 2.5 m on the Singularity Caul's statue, drawn five times its size.
SOLIDS = {
    'baelzharon': (['0x080006F7', '0x08000203'], '0xFF320000', 0.5, 'chiselled', 11),
}
# depth of relief, share of chisel strokes, pits, roughness and its spread.
LOOKS = {
    'chiselled': dict(depth=1.8, chisel=0.75, pits=1.4, rough=0.86, spread=0.05),
}


def spectral(rng, beta, lo=1, hi=1e9, angle=0.0, stretch=1.0):
    """Noise that repeats, its power falling with frequency, between bands in cycles a picture;
    `stretch` long along `angle` degrees."""
    f = np.fft.fftfreq(N) * N
    fy, fx = np.meshgrid(f, f, indexing='ij')
    c, s = np.cos(np.radians(angle)), np.sin(np.radians(angle))
    along, across = fx * c + fy * s, -fx * s + fy * c
    r = np.hypot(along * stretch ** 0.5, across / stretch ** 0.5)
    amp = np.where((r >= lo) & (r <= hi), 1 / np.maximum(r, 1) ** (beta / 2), 0)
    a = np.fft.ifft2(np.fft.fft2(rng.standard_normal((N, N))) * amp).real
    return ((a - a.mean()) / (a.std() + 1e-9)).astype(np.float32)


def write(path, a):
    if a.ndim == 2:
        a = np.stack([a, a, a], -1)
    a = np.concatenate([a, np.ones_like(a[..., :1])], -1)
    h, w, _ = a.shape
    subprocess.run(['magick', '-define', 'png:exclude-chunks=date,time', '-size', f'{w}x{h}', '-depth', '8',
                    'rgba:-', path], input=(np.clip(np.nan_to_num(a), 0, 1) * 255 + 0.5).astype(np.uint8).tobytes(),
                   check=True)


def stone(look, seed):
    """Weathered stone that repeats: broad lumps, chisel strokes, fine grain and pits."""
    k = LOOKS[look]
    rng = np.random.default_rng(seed)
    broad = spectral(rng, 3.2, 2, 24)
    chisel = spectral(rng, 2.0, 12, 90, angle=35, stretch=5.0)
    grain = spectral(rng, 1.0, 80)
    pits = np.zeros((N, N), np.float32)
    at = rng.integers(0, N, (900, 2))
    pits[at[:, 0], at[:, 1]] = rng.uniform(0.5, 1.0, 900)
    pits = ndimage.gaussian_filter(pits, 1.4, mode='wrap')
    pits /= pits.max()
    h = 0.55 * broad + k['chisel'] * chisel + 0.12 * grain - k['pits'] * pits
    h = (h - h.min()) / (h.max() - h.min())
    gy, gx = np.gradient(np.pad(h, 1, mode='wrap'))
    gy, gx = gy[1:-1, 1:-1], gx[1:-1, 1:-1]
    # Red along the picture's width, green up it.
    n = np.stack([-gx * 9.0 * k['depth'], gy * 9.0 * k['depth'], np.ones_like(h)], -1)
    n /= np.linalg.norm(n, axis=-1, keepdims=True)
    cavity = h - ndimage.gaussian_filter(h, 6, mode='wrap')
    occlusion = np.clip(1.0 + 3.0 * k['depth'] * np.minimum(cavity, 0), 0.45, 1.0)
    mottled = spectral(rng, 2.6, 2, 60)
    # A grey about 0.95, so the surface keeps its colour: darker in the hollows, lighter on the rises.
    colour = np.clip(0.95 + 0.04 * mottled + 0.5 * np.minimum(cavity, 0) + 0.3 * np.maximum(cavity, 0), 0.6, 1.0)
    rough = np.clip(k['rough'] + k['spread'] * spectral(rng, 2.0, 4, 80) - 0.9 * np.maximum(cavity, 0)
                    + 0.4 * pits, 0.2, 0.97)
    return colour, n * 0.5 + 0.5, rough, occlusion


def entry(name, surfaces, colour, size):
    files = f'materials/solid/{name}'
    return '\n'.join([
        '[[solid]]',
        'surface = [' + ', '.join(f'"{s}"' for s in surfaces) + ']',
        f'colour = "{colour}"',
        f'size = {size}',
        f'base_color = "{files}_colour.png"',
        f'normal = "{files}_normal.png"',
        # Twice as strong, so depth mapping's middle level draws it as made.
        'normal_scale = 2.0',
        f'roughness = "{files}_roughness.png"',
        f'occlusion = "{files}_occlusion.png"',
        'author = "Generated by solids.py from noise"',
        f'tool = "{TOOL}"',
        'license = "CC0-1.0"',
    ]) + '\n'


def main(pack):
    out = os.path.join(pack, 'materials', 'solid')
    os.makedirs(out, exist_ok=True)
    blocks = []
    for name, (surfaces, colour, size, look, seed) in SOLIDS.items():
        c, n, r, o = stone(look, seed)
        for part, a in (('colour', c), ('normal', n), ('roughness', r), ('occlusion', o)):
            write(os.path.join(out, f'{name}_{part}.png'), a)
        blocks.append(entry(name, surfaces, colour, size))
    path = os.path.join(pack, 'manifest.toml')
    text = open(path).read()
    # This script's earlier entries go; each runs from its [[solid]] line to the next table.
    text = re.sub(r'\n\[\[solid\]\]\n(?:(?!\n\[).)*?tool = "solids\.py"\n(?:(?!\n\[).)*', '', text, flags=re.S)
    open(path, 'w').write(text.rstrip('\n') + '\n\n' + '\n'.join(blocks))
    print(len(blocks), 'solid materials')


if __name__ == '__main__':
    main(sys.argv[1])

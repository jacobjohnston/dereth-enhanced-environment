# Silk for Ethangar's Robe, a custom item on Jacob's own Empyrean world: a normal and roughness
# picture for each of its pictures, and a [[material]] for each that keeps the picture the world
# serves (`keep_retail_picture`), so satin catches the sun with a soft sheen, and its brocade,
# jewels and beading shine more sharply. Its ids name no picture of the original game, so nothing
# else draws them. Reads the height and roughness the robe's painter wrote beside its pictures
# (8-bit, half the picture's size): nothing of any picture's pixels goes into the pack.
# Needs only Python and ImageMagick (`magick`).
# silk.py <the robe's art folder> <pack folder>
import math, os, re, subprocess, sys

# The robe's pictures: name, the id the world serves it as, and the painted picture's size.
PICTURES = [
    ('chest_a', 0x0500E300, 2048, 2048), ('chest_b', 0x0500E301, 2048, 2048),
    ('skirt_a', 0x0500E302, 2048, 2048), ('skirt_b', 0x0500E303, 2048, 2048),
    ('upper_leg', 0x0500E304, 2048, 1024), ('lower_leg', 0x0500E305, 2048, 2048),
    ('upper_arm', 0x0500E306, 1024, 2048), ('lower_arm', 0x0500E307, 1024, 2048),
    ('hood', 0x0500E308, 1024, 1024),
]
# How steeply a step of the whole height range across one texel bends the normal.
BEND = 6.0
# How much rougher than painted the silk is drawn, for a softer sheen.
ROUGHER = 1.6
# The colour a client without the robe's picture draws: its black satin.
FALLBACK = (8, 6, 14)


def write(path, w, h, rgba):
    subprocess.run(['magick', '-define', 'png:exclude-chunks=date,time', '-size', f'{w}x{h}', '-depth', '8',
                    'rgba:-', path], input=bytes(rgba), check=True)


def normal(hgt, w, h):
    out = bytearray(w * h * 4)
    at = lambda x, y: hgt[min(max(y, 0), h - 1) * w + min(max(x, 0), w - 1)] / 255
    for y in range(h):
        for x in range(w):
            nx = -(at(x + 1, y) - at(x - 1, y)) * 0.5 * BEND
            ny = (at(x, y + 1) - at(x, y - 1)) * 0.5 * BEND
            l = math.sqrt(nx * nx + ny * ny + 1)
            i = (y * w + x) * 4
            out[i:i + 4] = bytes((int((nx / l * 0.5 + 0.5) * 255 + 0.5), int((ny / l * 0.5 + 0.5) * 255 + 0.5),
                                  int((0.5 / l + 0.5) * 255 + 0.5), 255))
    return out


def main():
    art, pack = sys.argv[1:3]
    os.makedirs(os.path.join(pack, 'materials'), exist_ok=True)
    tables = ''
    for name, tid, pw, ph in PICTURES:
        w, h = pw // 2, ph // 2
        hgt = open(os.path.join(art, f'{name}.height'), 'rb').read()
        rgh = open(os.path.join(art, f'{name}.rough'), 'rb').read()
        assert len(hgt) == len(rgh) == w * h, name
        id_ = f'0x{tid:08X}'
        write(os.path.join(pack, f'materials/{id_}_normal.png'), w, h, normal(hgt, w, h))
        write(os.path.join(pack, f'materials/{id_}_roughness.png'), w, h,
              b''.join(bytes((q, q, q, 255)) for q in (min(255, round(r * ROUGHER)) for r in rgh)))
        write(os.path.join(pack, f'materials/{id_}_fallback.png'), 4, 4, bytes(FALLBACK + (255,)) * 16)
        tables += f'''
[[material]]
texture = "{id_}"
base_color = "materials/{id_}_fallback.png"
keep_retail_picture = true
normal = "materials/{id_}_normal.png"
roughness = "materials/{id_}_roughness.png"
normal_scale = 1.0
author = "Generated by silk.py"
tool = "silk.py"
license = "CC0-1.0"
'''
        print(name, id_, f'{w}x{h}')
    # Replace the robe's tables from an earlier run, and add them after the rest.
    path = os.path.join(pack, 'manifest.toml')
    text = open(path).read()
    ids = {f'0x{t:08X}' for _, t, _, _ in PICTURES}
    blocks = re.split(r'\n(?=\[\[)', text)
    kept = [b for b in blocks if not (b.startswith('[[material]]') and re.search(r'texture = "([^"]+)"', b)
                                      and re.search(r'texture = "([^"]+)"', b).group(1) in ids)]
    open(path, 'w').write('\n'.join(kept).rstrip('\n') + '\n' + tables)


if __name__ == '__main__':
    main()

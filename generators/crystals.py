# The crystal creatures drawn as the crystal they are: a [[material]] for each family of their retail
# pictures that keeps the picture (`keep_retail_picture`) and says it is clear crystal, in its own
# colour and bending what lies behind it. The shards (Crystal Shard, Crystal of the Dark Isle and
# the rest) share their picture with the world's crystal clusters, told apart by the palettes their
# palette templates lay, so their materials name those palettes; relief.py's material for that
# picture is given the picture's own palette, which the clusters show, so run this after relief.py.
# The blue shards wear that same palette, so it is named as laid (`laid_palettes`): drawn where a
# creature's look lays it, which Pyreal tells apart from a picture's own; others draw them retail.
# The pillars' picture is theirs alone. The bloodstones keep retail's look: their red is a glow,
# which a clear body, coloured by its picture alone, would lose. Writes a flat base colour for each,
# for a reader that draws no retail picture; nothing of any picture's pixels goes into the pack.
# Replaces any other generator's material for the pillars' picture.
# Needs Python and ImageMagick (`magick`).
# crystals.py <pack folder>
import os, re, subprocess, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import variants

TOOL = 'crystals.py'
SHARD = '0x05000E18'
# The shards' picture's own palette: the clusters' and the blue shards'.
OWN = '0x04000BEF'
# The shards' palettes (clothing 0x10000193, 0x1000019C to 0x1000019E, 0x10000485 and 0x100007D8's
# templates), and the blue 0x04000BEF where a look lays it.
SHARD_PALETTES = ['0x04000BEE', '0x04000BF0', '0x04000BF1', '0x04000BF2', '0x04000BF3', '0x04000BF4',
                  '0x04000BF5', '0x04000BF6', '0x04000FDC', '0x04000FDD', '0x04000FDE',
                  '0x0400151D', '0x0400151E', '0x0400151F', '0x04001520']
# The black shards (Crystal of the Dark Isle, Shard of the Herald): a clear material takes its
# colour from its picture's hue alone, so they keep more of their dark picture.
DARK_PALETTES = ['0x04000BF7', '0x04001521']

# Each family: its name, its retail picture, the palettes it is drawn in (any, where none), its flat
# colour and what it is made of.
FAMILIES = [
    ('crystal-shard', SHARD, SHARD_PALETTES, (0.45, 0.55, 0.85),
     f'laid_palettes = ["{OWN}"]\nclear = 0.65\nrefraction = 1.75'),
    ('crystal-shard-dark', SHARD, DARK_PALETTES, (0.12, 0.12, 0.14), 'clear = 0.25\nrefraction = 1.75'),
    # The cistern cores and pillars: a cut diamond's facets.
    ('crystal-pillar', '0x05001F99', [], (0.8, 0.8, 0.85), 'clear = 0.65\nrefraction = 2.0'),
]

# The 2005 files' pictures (1999's shard picture is the same), smaller than end of retail's, as
# `pyreal-art pictures` fingerprints them: each family is written for them too.
OLDER = {SHARD: 'picture 64x64 000000109e3f3f7f', '0x05001F99': 'picture 256x256 c3c31ab93311dff1'}


def write_flat(path, rgb):
    px = bytes(int(c * 255 + 0.5) for c in rgb) + b'\xff'
    subprocess.run(['magick', '-define', 'png:exclude-chunks=date,time', '-size', '4x4', '-depth', '8', 'rgba:-', path],
                   input=px * 16, check=True)


def main(pack):
    out = os.path.join(pack, 'materials'); os.makedirs(out, exist_ok=True)
    path = os.path.join(pack, 'manifest.toml')
    blocks = re.split(r'\n(?=\[\[)', variants.flat(open(path).read()))
    alone = {t for _, t, ps, _, _ in FAMILIES if not ps}
    texture = lambda b: set(re.findall(r'0x[0-9A-Fa-f]{8}', (re.search(r'^texture = (.*)$', b, re.M) or [None, ''])[1]))
    gone = [b for b in blocks if b.startswith('[[material]]') and (texture(b) & alone or re.search(rf'^tool = "{TOOL}"', b, re.M))]
    kept = [b for b in blocks if b not in gone]
    # Two materials on one picture each name their palettes: the clusters keep relief.py's.
    kept = [re.sub(r'^(texture = .*\n)', rf'\1palettes = ["{OWN}"]\n', b, count=1, flags=re.M)
            if b.startswith('[[material]]') and texture(b) == {SHARD} and not re.search(r'^palettes = ', b, re.M) else b
            for b in kept]
    # The pictures only the materials that go named go with them.
    keep = set(re.findall(r'"(materials/[^"]+\.png)"', '\n'.join(kept)))
    for b in gone:
        for f in re.findall(r'"(materials/[^"]+\.png)"', b):
            if f not in keep and os.path.exists(os.path.join(pack, f)):
                os.remove(os.path.join(pack, f))
    tables = ''
    for name, t, palettes, rgb, what in FAMILIES:
        base = f'materials/{name}_fallback.png'
        write_flat(os.path.join(pack, base), rgb)
        named = f'palettes = [{", ".join(chr(34) + p + chr(34) for p in palettes)}]\n' if palettes else ''
        for print_ in ['', f'fingerprint = "{OLDER[t]}"\n']:
            tables += (f'\n[[material]]\ntexture = "{t}"\n{print_}{named}'
                       f'base_color = "{base}"\nkeep_retail_picture = true\n{what}\n'
                       f'author = "Generated by {TOOL}"\ntool = "{TOOL}"\nlicense = "CC0-1.0"\n')
    open(path, 'w').write(variants.settle('\n'.join(kept).rstrip('\n') + '\n' + tables))
    print(2 * len(FAMILIES), 'materials;', len(gone), 'replaced')


if __name__ == '__main__':
    main(sys.argv[1])
